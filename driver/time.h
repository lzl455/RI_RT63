//=============================================================================;
// 配置引用区                                                                  ;
//=============================================================================;
//****************************************************************************************************
//Bit 7 TC0EN: TC0模块使能位
//1 = 使能TC0
//0 = 关闭TC0
//Bit 6 TC0MOD: TC0模式选择位
//1 = 16位模式
//0 = 8位模式
//Bit 5 T0HOSCS: 定时器高频振荡器选择
//1 = 选择与CPU不同的高频振荡器
//0 = 选择与CPU相同的高频振荡器
//Bit[4:3] TC0CKS[1:0]: TC0时钟源选择
//00	Foscl(低频系统时钟)
//01	Fosch(高频系统时钟)
//10	Fcpu
//11	T0cki(TC0)
//Bit[2:0] TC0CKPS[2:0]: TCx预分频比选择
//000	1:1
//001	1:2
//010	1:4
//011	1:8
//100	1:16
//101	1:32
//110	1:64
//111	1:128
#define			TC0EN_1          	0x80        // Bin(10000000)		//1 = 使能TC0
#define         TC0EN_0          	0x00        // Bin(00000000)       //0 = 关闭TC0
#define         TC0MOD_1        	0x40        // Bin(01000000)       //1 = 16位模式
#define         TC0MOD_0        	0x00        // Bin(00000000)       //0 = 8位模式
#define         T0HOSCS_1        	0x20        // Bin(00100000)       //1 = 选择与CPU不同的高频振荡器
#define         T0HOSCS_0        	0x00        // Bin(00000000)       //0 = 选择与CPU相同的高频振荡器
#define         TC0CKS_Foscl     	0x00        // Bin(00000000)       //Foscl(低频系统时钟)
#define         TC0CKS_Fosch     	0x08        // Bin(00001000)       //Fosch(高频系统时钟)
#define         TC0CKS_Fcpu      	0x10        // Bin(00010000)       //Fcpu
#define         TC0CKS_TC0CKI    	0x18        // Bin(00011000)      	//T0cki(TC0)
#define         TC0CKPS_1_1      	0x00        // Bin(00000000)      	//1:1分频
#define         TC0CKPS_1_2      	0x01        // Bin(00000001)       //1:2分频
#define         TC0CKPS_1_4      	0x02        // Bin(00000010)       //1:4分频
#define         TC0CKPS_1_8      	0x03        // Bin(00000011)       //1:8分频
#define         TC0CKPS_1_16     	0x04        // Bin(00000100)      	//1:16分频
#define         TC0CKPS_1_32     	0x05        // Bin(00000101)     	//1:32分频
#define         TC0CKPS_1_64     	0x06        // Bin(00000110)       //1:64分频
#define         TC0CKPS_1_128    	0x07        // Bin(00000111)       //1:128分频

