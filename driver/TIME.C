void timer0_init(void)
{
//1、时钟源设置
    T0CR =0x14;
    TC0CH = 0x00;                               // TC0计数器高位清零
    TC0CL = 0x62;                               // TC0计数器低位清零
//2、使能TC0,开启TC0中断
    TC0IF = 0;                                  // TC0中断标志清零
    TC0EN = 1;                                  // 使能TC0
    TC0IE = 1;                                  // 使能TC0溢出中断
}

void timer0_off(void)
{
    TC0IF = 0;
    TC0EN = 0;
    TC0IE = 0;
}

/******************************************************************************
* 函数名称: delayms()
* 功能描述: 毫秒延时程序
* 输入参数: 延时时间
* 输出参数: 无
* 说    明: 单位：1ms；最大：255ms
******************************************************************************/
void delayms(unsigned char time)
{
    unsigned int i;

    do
    {
        i=1000;
        while(--i);
    }
    while(--time);
}

/******************************************************************************
* 函数名称: delayus()
* 功能描述: 微秒延时
* 输入参数: 延时时间
* 输出参数: 无
* 说    明: 单位：1us；最大：256微秒；额外开销3.4us
******************************************************************************/
void delayus(unsigned char time)
{
    while(--time);
}
