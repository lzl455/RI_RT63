void led_mode_single(void)
{
    if(led_speed_lev>led_delay_count)
    {
		led_delay_count++;
        return;
	}
    led_delay_count = 0;

    rgb_enable = rgb_en_tbl[led_rgb_index&0x0F];
    for(gtemp_x=0; gtemp_x<iLED_NUM_MAX; gtemp_x++)
    {
        if(0 != pwm_duty_array_0[gtemp_x])
        {
    		pwm_duty_array_0[gtemp_x]--;

	        if(iRGB_QICAI <= led_rgb_index)
                rgb_enable = pwm_duty_array_1[gtemp_x];

            gtemp_j = gtemp_x; //led_to_matrix_tab_1[gtemp_x];
            rgb_pwm0_w();
        }
    }
}

